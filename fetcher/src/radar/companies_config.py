"""Read/write config/companies.yaml: the reviewable source of truth for how each company is fetched.

Each entry looks like:

    tekion:
      name: Tekion
      careers_url: https://tekion.com/careers
      source_type: greenhouse          # unknown | manual | greenhouse | lever | workday | playwright | ...
      source_config: {board: tekion}   # adapter-specific settings
      notes: ""                        # free text, e.g. why it's manual
      in_sheet: true                   # false once removed from the Excel (kept for history)
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, Any

import yaml

from radar.settings import COMPANIES_YAML

if TYPE_CHECKING:
    from radar.excel_import import CompanyRow

HEADER = """\
# How each company's jobs are fetched. Generated by `radar import-excel`, filled in by `radar detect`,
# and safe to edit by hand: change source_type / source_config, then run `radar import-excel` to sync.
# source_type: unknown | manual | greenhouse | lever | ashby | smartrecruiters | workable | workday |
#              eightfold | phenom | oracle_hcm | successfactors | pinpoint | <custom> | playwright
"""


def load_companies_yaml(path: Path = COMPANIES_YAML) -> dict[str, dict[str, Any]]:
    if not path.exists():
        return {}
    with open(path, encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    return {str(k): (v or {}) for k, v in data.items()}


def save_companies_yaml(entries: dict[str, dict[str, Any]], path: Path = COMPANIES_YAML) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(entries, sort_keys=False, allow_unicode=True, width=120, default_flow_style=False)
    path.write_text(HEADER + "\n" + body, encoding="utf-8")


def merge_sheet_into_yaml(entries: dict[str, dict[str, Any]], rows: list[CompanyRow]) -> dict[str, dict[str, Any]]:
    """Add new companies, refresh name/URL, keep existing source settings, flag removed ones."""
    by_url = {str(v.get("careers_url", "")).rstrip("/").lower(): k for k, v in entries.items()}
    merged: dict[str, dict[str, Any]] = {}
    for row in rows:
        old_key = row.slug if row.slug in entries else by_url.get(row.careers_url.rstrip("/").lower())
        old = entries.get(old_key, {}) if old_key else {}
        merged[row.slug] = {
            "name": row.name,
            "careers_url": row.careers_url,
            "source_type": old.get("source_type", "unknown"),
            "source_config": old.get("source_config") or {},
            "notes": old.get("notes", ""),
            "in_sheet": True,
        }
    for key, old in entries.items():  # keep removed companies at the end, flagged
        if key not in merged and key not in {by_url.get(r.careers_url.rstrip("/").lower()) for r in rows}:
            merged[key] = {**old, "in_sheet": False}
    return merged
